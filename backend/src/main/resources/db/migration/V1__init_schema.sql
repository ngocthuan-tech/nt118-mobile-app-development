-- ---------------------------------------------------------------- Người dùng
CREATE TABLE users (
    id                   VARCHAR(36)  PRIMARY KEY,          -- UUID
    email                VARCHAR(120) NOT NULL,
    password_hash        VARCHAR(100) NOT NULL,             -- BCrypt, không lưu mật khẩu gốc
    -- Hồ sơ
    display_name         VARCHAR(50)  NOT NULL,
    avatar_url           VARCHAR(500),
    height_cm            DOUBLE PRECISION,
    weight_kg            DOUBLE PRECISION,
    goal                 VARCHAR(20),                       -- lose_weight | build_muscle | stay_fit
    level                VARCHAR(20),                       -- beginner | intermediate | advanced
    weekly_goal_sessions INTEGER      NOT NULL DEFAULT 3,
    profile_completed    BOOLEAN      NOT NULL DEFAULT FALSE,
    active_plan_id       VARCHAR(64),                       -- giáo án đang theo
    plan_start_date      DATE,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Tiến độ (chỉ server cập nhật khi lưu buổi tập)
    streak               INTEGER      NOT NULL DEFAULT 0,   -- số ngày tập liên tiếp
    last_workout_date    DATE,                              -- ngày tập gần nhất, theo giờ Việt Nam
    weekly_xp            BIGINT       NOT NULL DEFAULT 0,
    week_key             VARCHAR(10),                       -- ví dụ 2026-W44
    total_xp             BIGINT       NOT NULL DEFAULT 0,
    total_reps           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- ---------------------------------------------------------------- Bài tập (9 bài, server nạp sẵn)
CREATE TABLE exercises (
    id              VARCHAR(40)  PRIMARY KEY,               -- squat, pushup, plank...
    name            VARCHAR(60)  NOT NULL,
    muscle_group    VARCHAR(20),                            -- legs | chest_arms | core | cardio
    difficulty      VARCHAR(10),                            -- easy | medium | hard
    image_name      VARCHAR(60),                            -- tên ảnh trong app
    description     VARCHAR(1000),
    measure_type    VARCHAR(10),                            -- reps | seconds
    default_sets    INTEGER          NOT NULL,
    default_reps    INTEGER          NOT NULL,
    calories_per_rep DOUBLE PRECISION NOT NULL,
    sort_order      INTEGER          NOT NULL
);

-- Các bước / mẹo / lỗi hay gặp của từng bài: mỗi dòng một câu, idx = thứ tự hiển thị
CREATE TABLE exercise_steps (
    exercise_id VARCHAR(40)  NOT NULL REFERENCES exercises (id),
    idx         INTEGER      NOT NULL,
    content     VARCHAR(500),
    PRIMARY KEY (exercise_id, idx)
);

CREATE TABLE exercise_tips (
    exercise_id VARCHAR(40)  NOT NULL REFERENCES exercises (id),
    idx         INTEGER      NOT NULL,
    content     VARCHAR(500),
    PRIMARY KEY (exercise_id, idx)
);

CREATE TABLE exercise_mistakes (
    exercise_id VARCHAR(40)  NOT NULL REFERENCES exercises (id),
    idx         INTEGER      NOT NULL,
    content     VARCHAR(500),
    PRIMARY KEY (exercise_id, idx)
);

-- ---------------------------------------------------------------- Giáo án
CREATE TABLE plans (
    id                  VARCHAR(64)  PRIMARY KEY,           -- fat-burn-4w, strength-4w, core-2w
    title               VARCHAR(100) NOT NULL,
    description         VARCHAR(500),
    level               VARCHAR(20),
    duration_days       INTEGER      NOT NULL,
    sessions_per_week   INTEGER      NOT NULL,
    minutes_per_session INTEGER      NOT NULL,
    cover_image_name    VARCHAR(60),
    sort_order          INTEGER      NOT NULL
);

-- Một bài trong một buổi của giáo án: buổi số day_index, bài exercise_id, sets × reps
CREATE TABLE plan_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id     VARCHAR(64) NOT NULL REFERENCES plans (id),
    day_index   INTEGER     NOT NULL,
    sort_order  INTEGER     NOT NULL,
    exercise_id VARCHAR(40) NOT NULL,
    sets        INTEGER     NOT NULL,
    reps        INTEGER     NOT NULL                        -- với bài tính giây (plank): số giây
);

-- ---------------------------------------------------------------- Buổi tập đã hoàn thành
CREATE TABLE workout_sessions (
    id            VARCHAR(36) PRIMARY KEY,
    user_id       VARCHAR(36) NOT NULL,
    exercise_id   VARCHAR(40) NOT NULL,
    exercise_name VARCHAR(60),
    started_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    duration_sec  INTEGER          NOT NULL,
    target_reps   INTEGER          NOT NULL,
    total_reps    INTEGER          NOT NULL,
    correct_reps  INTEGER          NOT NULL,
    accuracy      DOUBLE PRECISION NOT NULL,                -- 0..1 = correct_reps / total_reps
    calories      DOUBLE PRECISION NOT NULL,
    plan_id       VARCHAR(64),                              -- NULL nếu tập lẻ, không theo giáo án
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- Chuỗi 7 ngày và lịch sử đều truy vấn "buổi tập của 1 người trong khoảng thời gian"
CREATE INDEX idx_session_user_time ON workout_sessions (user_id, started_at);

-- Lỗi tư thế của một buổi: mã lỗi → số lần (knee_over_toe → 3)
CREATE TABLE session_form_errors (
    session_id  VARCHAR(36) NOT NULL REFERENCES workout_sessions (id),
    error_code  VARCHAR(40) NOT NULL,
    error_count BIGINT,
    PRIMARY KEY (session_id, error_code)
);

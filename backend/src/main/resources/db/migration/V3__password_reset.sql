-- =====================================================================
-- V3: Quên mật khẩu (Figma 08–11)
-- Mỗi lần người dùng bấm "Gửi mã xác thực" sinh một dòng. Chỉ lưu mã đã băm (BCrypt).
-- =====================================================================
CREATE TABLE password_reset_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     VARCHAR(36)  NOT NULL REFERENCES users (id),
    code_hash   VARCHAR(100) NOT NULL,                     -- BCrypt của mã 6 số
    attempts    INTEGER      NOT NULL DEFAULT 0,           -- số lần nhập sai
    used        BOOLEAN      NOT NULL DEFAULT FALSE,       -- đã dùng để đặt mật khẩu mới
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,      -- hết hạn sau 10 phút
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- Tìm mã mới nhất của một người dùng
CREATE INDEX idx_reset_codes_user_time ON password_reset_codes (user_id, created_at);

-- Đặt lại mật khẩu xong thì mọi token đăng nhập cấp TRƯỚC thời điểm này hết hiệu lực
-- (Figma 11: "đã đăng xuất tài khoản khỏi các thiết bị khác")
ALTER TABLE users ADD COLUMN password_changed_at TIMESTAMP(6) WITH TIME ZONE;
